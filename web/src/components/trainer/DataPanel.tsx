import { useId, useRef, useState } from 'react';
import type { DemoStatusDTO } from '#shared/domain/api.ts';
import { api, errorMessage } from '../../lib/api.ts';
import { plural } from '../../lib/format.ts';
import type { AsyncState } from '../../lib/hooks.ts';
import { useToast } from '../../lib/toast.tsx';
import { Icon } from '../Icon.tsx';
import { SkeletonBlock } from '../Page.tsx';
import { ConfirmDialog, type ConfirmTone } from './ConfirmDialog.tsx';

type ActionId = 'load' | 'remove-samples' | 'delete-practice' | 'reset-all';

interface Outcome {
  title: string;
  message: string;
}

interface ActionSpec {
  id: ActionId;
  rowTitle: string;
  rowText: string;
  button: string;
  available: boolean;
  unavailableText: string;
  dialog: {
    title: string;
    description: string;
    will: string[];
    wont: string[];
    confirm: string;
    pending: string;
    tone: ConfirmTone;
  };
  run(): Promise<Outcome>;
}

function loadedMessage(created: number, skipped: number): string {
  if (created === 0) {
    return skipped > 0
      ? `No new sample sessions were created. ${plural(skipped, 'sample session')} skipped because they are already loaded or unavailable.`
      : 'No sample sessions were created.';
  }
  const base = `Loaded ${plural(created, 'sample session')}, tagged Sample everywhere.`;
  return skipped > 0 ? `${base} ${plural(skipped, 'sample session')} skipped.` : base;
}

/** The four data actions, worded from the counts the server last reported. */
function buildActions(practice: number, samples: number): ActionSpec[] {
  const total = practice + samples;
  const practiceText = plural(practice, 'practice session');
  const sampleText = plural(samples, 'sample session');
  return [
    {
      id: 'load',
      rowTitle: 'Load sample sessions',
      rowText:
        'Adds completed, labelled sample calls so History, Progress and Calibration have something to show if no live model is available. They are generated by the built-in engine and kept out of your own progress unless you include them.',
      button: 'Load sample sessions',
      available: samples === 0,
      unavailableText: `Already loaded (${sampleText}). Remove them first to load them again.`,
      dialog: {
        title: 'Load sample sessions?',
        description:
          'This adds completed sample calls to the data linked to this browser, so History, Progress and Calibration have something to show.',
        will: [
          'Creates a small set of completed sessions, each with a transcript, a coaching report and a synthetic mentor review.',
          'Tags every one as Sample. The trainee lines are pre-written; the customer replies and reports come from the built-in rules engine, even if a live model is configured.',
        ],
        wont: ['Your own practice sessions are not changed.'],
        confirm: 'Load sample sessions',
        pending: 'Loading sample sessions\u2026',
        tone: 'primary',
      },
      async run() {
        const result = await api.loadSamples();
        return {
          title: result.created > 0 ? 'Sample sessions loaded' : 'No new sample sessions',
          message: loadedMessage(result.created, result.skipped),
        };
      },
    },
    {
      id: 'remove-samples',
      rowTitle: 'Remove sample sessions',
      rowText: 'Deletes only the sample sessions. Your own practice sessions stay.',
      button: 'Remove sample sessions',
      available: samples > 0,
      unavailableText: 'There are no sample sessions to remove.',
      dialog: {
        title: `Remove ${sampleText}?`,
        description: `This permanently deletes the ${sampleText} loaded for this browser, with their transcripts, reports and synthetic mentor reviews.`,
        will: [`Deletes ${sampleText}, including their transcripts, reports and mentor reviews.`],
        wont: [`Your ${practiceText} are not affected.`],
        confirm: 'Remove sample sessions',
        pending: 'Removing\u2026',
        tone: 'danger',
      },
      async run() {
        const result = await api.resetDemo('samples');
        return {
          title: 'Sample sessions removed',
          message: `Removed ${plural(result.deleted, 'sample session')}.`,
        };
      },
    },
    {
      id: 'delete-practice',
      rowTitle: 'Delete my practice sessions',
      rowText:
        'Deletes the sessions you ran yourself, with their transcripts, reports and mentor scores. Sample sessions stay.',
      button: 'Delete my practice sessions',
      available: practice > 0,
      unavailableText: 'You have no practice sessions to delete.',
      dialog: {
        title: `Delete ${practiceText}?`,
        description: `This permanently deletes the ${practiceText} you ran in this browser, including any call in progress, with their transcripts, coaching reports and mentor scores. This cannot be undone.`,
        will: [
          `Deletes ${practiceText}, including their transcripts, coaching reports and mentor scores.`,
        ],
        wont: [
          `Your ${sampleText} are not affected.`,
          'Your theme and motion preferences are not affected.',
        ],
        confirm: 'Delete practice sessions',
        pending: 'Deleting\u2026',
        tone: 'danger',
      },
      async run() {
        const result = await api.resetDemo('practice');
        return {
          title: 'Practice sessions deleted',
          message: `Deleted ${plural(result.deleted, 'practice session')}.`,
        };
      },
    },
    {
      id: 'reset-all',
      rowTitle: 'Reset everything',
      rowText:
        'Deletes all practice and sample sessions linked to this browser, for a clean start.',
      button: 'Reset everything',
      available: total > 0,
      unavailableText: 'There is nothing to reset.',
      dialog: {
        title: 'Reset all demo data?',
        description: `This permanently deletes ${plural(total, 'session')} linked to this browser: ${practiceText} and ${sampleText}, with all their transcripts, reports and mentor scores. This cannot be undone.`,
        will: [
          `Deletes ${practiceText}, including any call in progress.`,
          `Deletes ${sampleText}.`,
          'Deletes every transcript, coaching report and mentor score that belongs to them.',
        ],
        wont: ['Your theme and motion preferences are not affected.'],
        confirm: 'Delete everything',
        pending: 'Deleting\u2026',
        tone: 'danger',
      },
      async run() {
        const result = await api.resetDemo('all');
        return {
          title: 'Demo data reset',
          message: `Reset complete. Deleted ${plural(result.deleted, 'session')}.`,
        };
      },
    },
  ];
}

/**
 * Counts and the actions that change them. Every action is confirmed in a dialog that spells out
 * what will be created or deleted, and the result is announced and the counts refreshed.
 */
export function DataPanel({ status }: { status: AsyncState<DemoStatusDTO> }) {
  const titleId = useId();
  const rowId = useId();
  const { toast } = useToast();
  const busy = useRef(false);
  const [openId, setOpenId] = useState<ActionId | null>(null);
  const [pending, setPending] = useState(false);
  const [dialogError, setDialogError] = useState<string | null>(null);
  const [message, setMessage] = useState('');

  const counts = status.data;
  const specs = buildActions(counts?.practiceSessions ?? 0, counts?.sampleSessions ?? 0);
  const open = specs.find((spec) => spec.id === openId) ?? null;

  async function confirm() {
    if (!open || busy.current) return;
    busy.current = true;
    setPending(true);
    setDialogError(null);
    try {
      const outcome = await open.run();
      setOpenId(null);
      setMessage(outcome.message);
      toast({ tone: 'positive', title: outcome.title });
      status.reload();
    } catch (error) {
      setDialogError(errorMessage(error));
    } finally {
      busy.current = false;
      setPending(false);
    }
  }

  return (
    <section className="glass card stack tr-data" aria-labelledby={titleId}>
      <div className="tr-data-head">
        <div>
          <h2 id={titleId} className="t-section">
            Demo data
          </h2>
          <p className="t-small t-muted">
            Counts are for sessions linked to this browser. They are stored on the machine that runs
            Firefly&rsquo;s server.
          </p>
        </div>
        {counts ? (
          <dl className="tr-counts">
            <div>
              <dt>Practice sessions</dt>
              <dd className="tabular">{counts.practiceSessions}</dd>
            </div>
            <div>
              <dt>Sample sessions</dt>
              <dd className="tabular">{counts.sampleSessions}</dd>
            </div>
          </dl>
        ) : null}
      </div>

      <div>
        {!counts ? (
          status.error ? (
            <div className="callout callout-negative" role="alert">
              <Icon name="alert" size={18} />
              <div className="stack" style={{ ['--stack-gap' as string]: 'var(--sp-3)' }}>
                <p>The session counts could not be loaded, so the data actions are unavailable.</p>
                <div>
                  <button
                    type="button"
                    className="btn btn-secondary btn-sm"
                    onClick={status.reload}
                  >
                    <Icon name="refresh" size={16} /> Try again
                  </button>
                </div>
              </div>
            </div>
          ) : (
            <div className="stack" role="status" aria-label="Loading session counts">
              <SkeletonBlock height={64} />
              <SkeletonBlock height={64} />
            </div>
          )
        ) : (
          <ul role="list" className="tr-data-actions">
            {specs.map((spec) => {
              const unavailable = !spec.available || pending;
              const textId = `${rowId}-${spec.id}`;
              return (
                <li key={spec.id} className="tr-action">
                  <div className="tr-action-text">
                    <p className="tr-action-title">{spec.rowTitle}</p>
                    <p id={textId} className="t-small t-muted">
                      {spec.rowText}
                      {spec.available ? null : <> {spec.unavailableText}</>}
                    </p>
                  </div>
                  <button
                    type="button"
                    className="btn btn-secondary"
                    aria-disabled={unavailable || undefined}
                    aria-describedby={textId}
                    onClick={() => {
                      if (unavailable) return;
                      setDialogError(null);
                      setOpenId(spec.id);
                    }}
                  >
                    {spec.button}
                  </button>
                </li>
              );
            })}
          </ul>
        )}
        <p role="status" className="tr-status">
          {message}
        </p>
      </div>

      {open ? (
        <ConfirmDialog
          title={open.dialog.title}
          description={open.dialog.description}
          will={open.dialog.will}
          wont={open.dialog.wont}
          confirmLabel={open.dialog.confirm}
          pendingLabel={open.dialog.pending}
          tone={open.dialog.tone}
          pending={pending}
          error={dialogError}
          onConfirm={() => void confirm()}
          onCancel={() => setOpenId(null)}
        />
      ) : null}
    </section>
  );
}
