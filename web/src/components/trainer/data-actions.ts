import { api } from '../../lib/api.ts';
import { plural } from '../../lib/format.ts';

export type ActionId = 'load' | 'remove-samples' | 'delete-practice' | 'reset-all';
export type ConfirmTone = 'danger' | 'primary';

export interface Outcome {
  title: string;
  message: string;
}

export interface ActionSpec {
  id: ActionId;
  rowTitle: string;
  rowText: string;
  button: string;
  available: boolean;
  unavailableText: string;
  dialog: {
    title: string;
    description: string;
    will: string[];
    wont: string[];
    confirm: string;
    pending: string;
    tone: ConfirmTone;
  };
}

export function loadedMessage(created: number, skipped: number): string {
  if (created === 0) {
    return skipped > 0
      ? `No new sample sessions were created. ${plural(skipped, 'sample session')} skipped because they are already loaded or unavailable.`
      : 'No sample sessions were created.';
  }
  const base = `Loaded ${plural(created, 'sample session')}, tagged Sample everywhere.`;
  return skipped > 0 ? `${base} ${plural(skipped, 'sample session')} skipped.` : base;
}

/** The four data actions, worded from the counts the server last reported. */
export function buildActions(practice: number, samples: number): ActionSpec[] {
  const total = practice + samples;
  const practiceText = plural(practice, 'practice session');
  const sampleText = plural(samples, 'sample session');
  return [
    {
      id: 'load',
      rowTitle: 'Load sample sessions',
      rowText:
        'Adds completed, labelled sample calls so History, Progress and Calibration have something to show if no live model is available. They are generated by the built-in engine and kept out of your own progress unless you include them.',
      button: 'Load sample sessions',
      available: samples === 0,
      unavailableText: `Already loaded (${sampleText}). Remove them first to load them again.`,
      dialog: {
        title: 'Load sample sessions?',
        description:
          'This adds completed sample calls to the data linked to this browser, so History, Progress and Calibration have something to show.',
        will: [
          'Creates a small set of completed sessions, each with a transcript, a coaching report and a synthetic mentor review.',
          'Tags every one as Sample. The trainee lines are pre-written; the customer replies and reports come from the built-in rules engine, even if a live model is configured.',
        ],
        wont: ['Your own practice sessions are not changed.'],
        confirm: 'Load sample sessions',
        pending: 'Loading sample sessions\u2026',
        tone: 'primary',
      },
    },
    {
      id: 'remove-samples',
      rowTitle: 'Remove sample sessions',
      rowText: 'Deletes only the sample sessions. Your own practice sessions stay.',
      button: 'Remove sample sessions',
      available: samples > 0,
      unavailableText: 'There are no sample sessions to remove.',
      dialog: {
        title: `Remove ${sampleText}?`,
        description: `This permanently deletes the ${sampleText} loaded for this browser, with their transcripts, reports and synthetic mentor reviews.`,
        will: [`Deletes ${sampleText}, including their transcripts, reports and mentor reviews.`],
        wont: [`Your ${practiceText} are not affected.`],
        confirm: 'Remove sample sessions',
        pending: 'Removing\u2026',
        tone: 'danger',
      },
    },
    {
      id: 'delete-practice',
      rowTitle: 'Delete my practice sessions',
      rowText:
        'Deletes the sessions you ran yourself, with their transcripts, reports and mentor scores. Sample sessions stay.',
      button: 'Delete my practice sessions',
      available: practice > 0,
      unavailableText: 'You have no practice sessions to delete.',
      dialog: {
        title: `Delete ${practiceText}?`,
        description: `This permanently deletes the ${practiceText} you ran in this browser, including any call in progress, with their transcripts, coaching reports and mentor scores. This cannot be undone.`,
        will: [
          `Deletes ${practiceText}, including their transcripts, coaching reports and mentor scores.`,
        ],
        wont: [
          `Your ${sampleText} are not affected.`,
          'Your theme and motion preferences are not affected.',
        ],
        confirm: 'Delete practice sessions',
        pending: 'Deleting\u2026',
        tone: 'danger',
      },
    },
    {
      id: 'reset-all',
      rowTitle: 'Reset everything',
      rowText:
        'Deletes all practice and sample sessions linked to this browser, for a clean start.',
      button: 'Reset everything',
      available: total > 0,
      unavailableText: 'There is nothing to reset.',
      dialog: {
        title: 'Reset all demo data?',
        description: `This permanently deletes ${plural(total, 'session')} linked to this browser: ${practiceText} and ${sampleText}, with all their transcripts, reports and mentor scores. This cannot be undone.`,
        will: [
          `Deletes ${practiceText}, including any call in progress.`,
          `Deletes ${sampleText}.`,
          'Deletes every transcript, coaching report and mentor score that belongs to them.',
        ],
        wont: ['Your theme and motion preferences are not affected.'],
        confirm: 'Delete everything',
        pending: 'Deleting\u2026',
        tone: 'danger',
      },
    },
  ];
}

/** Does what the action says and reports it in words. Throws what the server threw. */
export async function runAction(id: ActionId): Promise<Outcome> {
  switch (id) {
    case 'load': {
      const result = await api.loadSamples();
      return {
        title: result.created > 0 ? 'Sample sessions loaded' : 'No new sample sessions',
        message: loadedMessage(result.created, result.skipped),
      };
    }
    case 'remove-samples': {
      const result = await api.resetDemo('samples');
      return {
        title: 'Sample sessions removed',
        message: `Removed ${plural(result.deleted, 'sample session')}.`,
      };
    }
    case 'delete-practice': {
      const result = await api.resetDemo('practice');
      return {
        title: 'Practice sessions deleted',
        message: `Deleted ${plural(result.deleted, 'practice session')}.`,
      };
    }
    case 'reset-all': {
      const result = await api.resetDemo('all');
      return {
        title: 'Demo data reset',
        message: `Reset complete. Deleted ${plural(result.deleted, 'session')}.`,
      };
    }
  }
}
