import type { ProgressDTO } from '#shared/domain/api.ts';
import { scenarioForSkill } from '#shared/domain/recommend.ts';
import type { DimensionId } from '#shared/domain/vocab.ts';
import { api } from '../../lib/api.ts';
import { useApi } from '../../lib/hooks.ts';
import { Icon } from '../Icon.tsx';
import { FocusCard } from './FocusCard.tsx';
import { Opportunities } from './Opportunities.tsx';
import { SkillsSection } from './SkillsSection.tsx';
import { SummaryTiles } from './SummaryTiles.tsx';

/**
 * Everything on My progress once there is a completed call to show. The numbers all come from the
 * progress summary; the scenario list and the saved calls are only used to point each skill at a
 * scenario built to practise it, so the page is complete without them.
 */
export function ProgressView({
  progress,
  includeSamples,
  busy,
}: {
  progress: ProgressDTO;
  /** Whether these numbers include the built-in sample sessions. */
  includeSamples: boolean;
  busy: boolean;
}) {
  const scenarios = useApi((signal) => api.scenarios(signal), []);
  // Sample calls are demonstration data, so they never steer which scenario is suggested.
  const sessions = useApi(
    (signal) => api.listSessions({ limit: 100, includeSamples: false }, signal),
    [],
  );
  const waiting = scenarios.loading || sessions.loading;
  const library = scenarios.data;
  const calls = sessions.data?.sessions;
  const scenarioFor = (dimension: DimensionId) =>
    library && calls ? scenarioForSkill(library, calls, dimension) : null;

  return (
    <div className="pg-content" aria-busy={busy}>
      {includeSamples ? (
        <div className="callout callout-caution" role="note">
          <Icon name="info" size={18} />
          <p>
            <strong>Sample sessions are included.</strong> They were generated by Firefly&rsquo;s
            built-in engine, so these numbers do not describe your own practice. Switch the option
            above off to see only your own calls.
          </p>
        </div>
      ) : null}

      <SummaryTiles progress={progress} />

      <div className="pg-duo">
        <FocusCard
          progress={progress}
          scenario={progress.focus ? scenarioFor(progress.focus) : null}
          loading={waiting}
        />
        <Opportunities progress={progress} scenarioFor={scenarioFor} />
      </div>

      <SkillsSection progress={progress} />

      <p className="pg-note">
        <Icon name="shield-check" size={18} />
        <span>{progress.note}</span>
      </p>
    </div>
  );
}
