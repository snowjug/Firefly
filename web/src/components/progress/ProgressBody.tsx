import { useMemo } from 'react';
import type { ProgressDTO, SessionSummaryDTO } from '#shared/domain/api.ts';
import { assessMastery } from '#shared/domain/mastery.ts';
import { recommendMission } from '#shared/domain/recommend.ts';
import { api } from '../../lib/api.ts';
import { useApi } from '../../lib/hooks.ts';
import { MILESTONE_LOOKBACK, callsToInspect, useMilestones } from '../../lib/milestones.ts';
import { NextMission } from '../dashboard/NextMission.tsx';
import { Icon } from '../Icon.tsx';
import { SkeletonBlock } from '../Page.tsx';
import { MasteryHero } from './MasteryHero.tsx';
import { MilestonesSection } from './MilestonesSection.tsx';
import { PATH_LENGTH, PracticePath } from './PracticePath.tsx';
import { OpportunitiesSection, SummaryCards, TrendsSection } from './ProgressSections.tsx';
import '../../styles/progress.css';

const NO_SESSIONS: SessionSummaryDTO[] = [];

/**
 * Everything on the Progress page once there is practice to show: the skill constellations, the
 * next mission, the summary, each skill's history, the path of calls, the milestones and the
 * opportunities that keep coming up. The numbers come from the progress summary; the constellations,
 * path and milestones come from the saved calls and their reports.
 */
export function ProgressBody({
  progress,
  includeSamples,
  busy,
}: {
  progress: ProgressDTO;
  /** Whether these numbers include the built-in sample sessions. */
  includeSamples: boolean;
  busy: boolean;
}) {
  const scenarios = useApi((signal) => api.scenarios(signal), []);
  const sessions = useApi(
    (signal) => api.listSessions({ limit: 100, includeSamples }, signal),
    [includeSamples],
  );
  const ready = !sessions.loading && sessions.data !== null;
  const list = sessions.data?.sessions ?? NO_SESSIONS;

  const mastery = useMemo(() => assessMastery(list, { includeSamples }), [list, includeSamples]);
  const completed = useMemo(
    () => callsToInspect(list, includeSamples, list.length),
    [list, includeSamples],
  );
  const milestones = useMilestones(ready ? completed.slice(0, MILESTONE_LOOKBACK) : NO_SESSIONS);

  // Sample calls are demonstration data, so they never steer a recommendation.
  const recommendation = useMemo(
    () =>
      !ready || includeSamples || !scenarios.data
        ? null
        : recommendMission({ scenarios: scenarios.data, sessions: list, progress }),
    [ready, includeSamples, scenarios.data, list, progress],
  );

  const opportunities = (
    <OpportunitiesSection
      progress={progress}
      scenarios={scenarios.data ?? undefined}
      sessions={ready ? list : undefined}
    />
  );

  return (
    <div className="pg-content" aria-busy={busy}>
      {includeSamples ? (
        <div className="callout callout-caution" role="note">
          <Icon name="info" size={18} />
          <p>
            <strong>Sample sessions are included.</strong> They were generated by Firefly&rsquo;s
            built-in engine, so these numbers do not describe your own practice. Switch the option
            above off to see only your own calls.
          </p>
        </div>
      ) : null}

      {ready ? (
        <MasteryHero mastery={mastery} focus={progress.focus} includeSamples={includeSamples} />
      ) : sessions.error ? (
        <div className="pg-empty" role="alert">
          <p>We couldn&rsquo;t load your calls to draw your constellations.</p>
          <button type="button" className="btn btn-secondary btn-sm" onClick={sessions.reload}>
            Try again
          </button>
        </div>
      ) : (
        <div role="status" aria-label="Loading your constellations">
          <SkeletonBlock height={320} />
        </div>
      )}

      {recommendation ? <NextMission recommendation={recommendation} /> : null}

      <SummaryCards progress={progress} />
      <TrendsSection progress={progress} mastery={ready ? mastery : undefined} />

      {/* One wrapper in every state, so the opportunities are never remounted when the calls load. */}
      <div className={ready ? 'pg-duo' : 'pg-duo pg-duo-solo'}>
        {ready ? (
          <div className="pg-area-path">
            <PracticePath
              calls={completed.slice(0, PATH_LENGTH)}
              total={completed.length}
              includeSamples={includeSamples}
            />
          </div>
        ) : null}
        {ready ? (
          <div className="pg-area-ms">
            <MilestonesSection state={milestones} />
          </div>
        ) : null}
        <div className="pg-area-opp">{opportunities}</div>
      </div>

      <p className="pg-reminder t-meta">
        These numbers are practice signals from a handful of calls, not an assessment of you. They
        are never compared with other people.
      </p>
    </div>
  );
}
