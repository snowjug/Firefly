import type { CoachingReport } from '#shared/domain/report.ts';
import {
  CARE_LABELS,
  DIMENSIONS,
  scoreLabel,
  type DimensionId,
  type FactImportance,
} from '#shared/domain/vocab.ts';

// Plain-language wording shared by the report, transcript, history and progress screens.

export type Sufficiency = CoachingReport['dimensions'][number]['sufficiency'];
export type DiscoveryStatus = CoachingReport['discovery']['results'][number]['status'];
export type CurveballStatus = NonNullable<CoachingReport['curveball']>['status'];

/** "4" for whole scores and "3.7" for averages. */
export function scoreText(score: number): string {
  return Number.isInteger(score) ? String(score) : score.toFixed(1);
}

export const scoreOfFive = (score: number): string => `${scoreText(score)} of 5`;

/** "4 of 5 \u2013 Strong": the text that always accompanies a score meter. */
export const scoreWithLabel = (score: number): string =>
  `${scoreOfFive(score)} \u2013 ${scoreLabel(score)}`;

/** The badge shown when a skill rests on thin evidence (nothing for sufficient evidence). */
export const SUFFICIENCY_BADGE: Record<Sufficiency, string | null> = {
  sufficient: null,
  limited: 'Limited evidence',
  insufficient: 'Not enough evidence',
};

export const DISCOVERY_STATUS: Record<DiscoveryStatus, string> = {
  discovered: 'Found',
  partial: 'Partly found',
  missed: 'Missed',
};

export const IMPORTANCE_LABEL: Record<FactImportance, string> = {
  critical: 'Critical',
  important: 'Important',
  helpful: 'Helpful',
};

export const CURVEBALL_STATUS: Record<
  CurveballStatus,
  { label: string; tone: 'positive' | 'caution' | 'info' }
> = {
  resolved: { label: 'Handled', tone: 'positive' },
  unresolved: { label: 'Not resolved', tone: 'caution' },
  active: { label: 'Still open when the call ended', tone: 'info' },
};

export const dimensionLabel = (id: DimensionId): string => DIMENSIONS[id].label;

/** The CARE behaviours a skill supports, for example "Communicate effectively, Be empathetic". */
export function careHint(id: DimensionId): string {
  return DIMENSIONS[id].care.map((behaviour) => CARE_LABELS[behaviour]).join(', ');
}

export const reportHref = (sessionId: string): string =>
  `/sessions/${encodeURIComponent(sessionId)}/report`;

export function transcriptHref(sessionId: string, turn?: number | null): string {
  const base = `/sessions/${encodeURIComponent(sessionId)}/transcript`;
  return turn ? `${base}?turn=${turn}` : base;
}

