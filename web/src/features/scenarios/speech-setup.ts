import type { AppConfigDTO } from '#shared/domain/api.ts';
import type { SpeechCapabilitiesDTO } from '#shared/domain/speech.ts';
import {
  chooseCapture,
  choosePlayback,
  type CaptureKind,
  type PlaybackKind,
  type VoiceFeatures,
} from '../voice/support.ts';

// What the call brief says about the microphone, speech and the customer. Every sentence is chosen
// from what this server and this browser can really do, using the same decision the call screen
// makes (`chooseCapture` and `choosePlayback`), so the brief never promises more than the call does.

export interface SpeechSetup {
  capture: CaptureKind;
  playback: PlaybackKind;
  /** A spoken call can be held: the microphone can be used and something can turn speech into text. */
  canSpeak: boolean;
  /** Where the trainee's speech goes. */
  yourSpeech: string;
  /** How the customer's replies are voiced. */
  customerVoice: string;
  /** Why speech is degraded or off, from the server (safe to show), or null. */
  notice: string | null;
}

export const MICROPHONE_INTRO =
  'When you start a voice call, your browser asks to use your microphone. Firefly opens it only during the call and you can mute or stop it at any time.';

function yourSpeechFor(
  capture: CaptureKind,
  speech: SpeechCapabilitiesDTO,
  features: VoiceFeatures,
): string {
  if (capture === 'server-speech') {
    return speech.demo
      ? `Your speech is sent through Firefly to ${speech.label}. It does not understand audio and returns scripted text instead of what you said, so it is for trying the call out. Firefly does not store the audio.`
      : `Your speech is sent through Firefly to ${speech.label} and turned into text. Firefly does not store the audio.`;
  }
  if (capture === 'browser-recognition') {
    return "Your browser's speech recognition turns your speech into text. In Chrome and Edge the browser's own speech service may process your audio. Firefly receives text only and does not store audio.";
  }
  return features.secureContext
    ? 'Voice input is not available in this browser. You can type the whole call.'
    : 'Voice input is not available in this browser, because this page is not on a secure (https) connection. You can type the whole call.';
}

function customerVoiceFor(playback: PlaybackKind, speech: SpeechCapabilitiesDTO): string {
  if (playback === 'server-speech') {
    return speech.demo
      ? `The customer does not speak. ${speech.label} plays a short soft sound and the reply appears as text.`
      : `The customer's voice is synthetic, generated by ${speech.label}. It is not a recording of a real person.`;
  }
  if (playback === 'browser-synthesis') {
    return "The customer's voice is synthetic, spoken by your browser. It is not a recording of a real person.";
  }
  return "This browser cannot speak the customer's replies, so you read them on screen.";
}

export function describeSpeechSetup(
  speech: SpeechCapabilitiesDTO,
  features: VoiceFeatures,
): SpeechSetup {
  const capture = chooseCapture(speech, features);
  const playback = choosePlayback(speech, features);
  return {
    capture,
    playback,
    canSpeak: capture !== 'none',
    yourSpeech: yourSpeechFor(capture, speech, features),
    customerVoice: customerVoiceFor(playback, speech),
    notice: speech.notice,
  };
}

/** Who plays the customer: the built-in rules engine, or a named language model. */
export function describeCustomer(provider: AppConfigDTO['provider']): string {
  return provider.demo
    ? "Demo mode: the customer is played by Firefly's built-in rules engine."
    : `Live model: ${provider.label}. The customer's replies come from this language model.`;
}
