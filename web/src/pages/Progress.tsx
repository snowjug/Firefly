import { useState } from 'react';
import { useLocation } from 'react-router';
import {
  ErrorNotice,
  LoadingNotice,
  PageFrame,
  PageHead,
  Toggle,
} from '../components/frame/index.ts';
import { NothingYet } from '../components/progress/NothingYet.tsx';
import { Opportunities } from '../components/progress/Opportunities.tsx';
import { ProgressStage } from '../components/progress/ProgressStage.tsx';
import { ScoresMore } from '../components/progress/ScoresMore.tsx';
import { usePracticeLookups } from '../components/progress/usePracticeLookups.ts';
import { useScrollToHash } from '../components/progress/useScrollToHash.ts';
import { Recognition } from '../components/rewards/Recognition.tsx';
import { useWorldPose } from '../components/world/useWorldPose.ts';
import { api } from '../lib/api.ts';
import { useApi } from '../lib/hooks.ts';
import '../styles/progress.css';
import '../styles/rewards.css';

/** Arriving from a report (`/progress?from=report`, or router state): the newest stars pulse once. */
function useArrivedFromReport(): boolean {
  const location = useLocation();
  const state = location.state as { from?: unknown } | null;
  return state?.from === 'report' || new URLSearchParams(location.search).get('from') === 'report';
}

/**
 * How practice is going, skill by skill, as a constellation lit only by evidence, and what to work
 * on next, with the recognition (points, badges, challenges) below it. Sample sessions are left out
 * unless asked for, and the page says so whenever they are in.
 */
export default function Progress() {
  const [includeSamples, setIncludeSamples] = useState(false);
  // The answer carries the setting it was asked with, so sample numbers are never shown as your own.
  const state = useApi(
    async (signal) => ({ includeSamples, progress: await api.progress(includeSamples, signal) }),
    [includeSamples],
  );
  // "Today" for a streak is the learner's own day, so the browser's offset goes with the request.
  const rewards = useApi((signal) => api.rewards(new Date().getTimezoneOffset(), signal), []);
  const data = state.data;
  const stale = state.loading && data !== null && data.includeSamples !== includeSamples;
  const hasCalls = data !== null && data.progress.completedSessions > 0;
  const practice = usePracticeLookups(hasCalls);
  const arrivedFromReport = useArrivedFromReport();
  useWorldPose({ intensity: 0.3, warmth: arrivedFromReport ? 0.52 : undefined });
  // `/rewards` lands on #recognition: wait until everything above it has settled too, or the section
  // would move after the page had scrolled to it.
  useScrollToHash(!state.loading && !rewards.loading && !practice.waiting);

  let stage;
  if (!data) {
    stage = state.error ? (
      <div className="pg-hero__panel">
        <ErrorNotice
          error={state.error}
          onRetry={state.reload}
          title="We couldn’t load your progress"
        />
      </div>
    ) : (
      <div className="pg-hero__sky">
        <LoadingNotice label="Loading your progress" lines={7} />
      </div>
    );
  } else if (!hasCalls) {
    stage = <NothingYet includeSamples={data.includeSamples} />;
  } else {
    stage = (
      <ProgressStage
        progress={data.progress}
        scenarioFor={practice.scenarioFor}
        practiceLoading={practice.waiting}
        arrivedFromReport={arrivedFromReport}
      />
    );
  }

  return (
    <PageFrame title="My progress" width="wide" className="pg">
      <div
        className="pg-hero pg-content"
        aria-busy={stale}
        data-state={!data ? (state.error ? 'error' : 'loading') : 'ready'}
      >
        <div className="pg-hero__head">
          <PageHead
            eyebrow="Progress / The skill constellation"
            title={
              <>
                My <em>progress</em>
              </>
            }
            lead="Six skills, lit one completed call at a time."
          />
        </div>
        {stage}
        <div className="pg-hero__tools">
          <Toggle
            checked={includeSamples}
            onChange={setIncludeSamples}
            label="Include sample sessions"
            hint="Samples are pre-generated by the built-in engine, so they are left out unless you switch this on."
          />
          {data?.includeSamples ? (
            <p className="pg-note" role="note">
              <strong>Sample sessions are included.</strong> They were generated by Firefly&rsquo;s
              built-in engine, so these numbers do not describe your own practice. Switch the option
              above off to see only your own calls.
            </p>
          ) : null}
        </div>
      </div>
      {hasCalls ? <ScoresMore progress={data.progress} /> : null}
      {hasCalls ? (
        <Opportunities progress={data.progress} scenarioFor={practice.scenarioFor} />
      ) : null}
      {hasCalls ? <p className="pg-footnote">{data.progress.note}</p> : null}
      {/* Not painted until the sky has loaded or failed: it sits below the sky, and would otherwise be
          pushed off the screen as a visible shift when the sky arrives. It is in the page all along,
          so the address /progress#recognition still has its target. */}
      <div className="pg-below" data-waiting={!data && !state.error ? '' : undefined}>
        <Recognition rewards={rewards} />
      </div>
    </PageFrame>
  );
}
